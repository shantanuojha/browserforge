#!/usr/bin/env node
/**
 * Regenerates public/rules/tracking-params.json (static DNR ruleset) from the
 * ClearURLs catalog. Run from the extension directory:
 *
 *   node scripts/build-tracking-rules.mjs [--offline] [--source <path-or-url>]
 *
 * The output is checked in and never fetched at runtime (Chrome Web Store
 * "no remote code/config" policy). Requires Node >= 22.6 (type stripping is
 * used to share the TypeScript compiler code in src/lib/tracking).
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DNR_LIMITS } from "../src/lib/dnr.ts";
import {
  FALLBACK_PROVIDERS,
  parseClearUrlsCatalog,
  toRemoveParamsRules,
} from "../src/lib/tracking/catalog.ts";

const CATALOG_URL = "https://rules2.clearurls.xyz/data.minify.json";
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outDir = path.join(root, "public", "rules");
const rulesPath = path.join(outDir, "tracking-params.json");
const metaPath = path.join(outDir, "tracking-params.meta.json");
const attributionPath = path.join(outDir, "ATTRIBUTION.md");

const args = process.argv.slice(2);
const offline = args.includes("--offline");
const sourceIdx = args.indexOf("--source");
const source = sourceIdx !== -1 ? args[sourceIdx + 1] : CATALOG_URL;

async function loadCatalog() {
  if (offline) return { json: null, from: "offline flag" };
  try {
    if (/^https?:/.test(source)) {
      const res = await fetch(source, { signal: AbortSignal.timeout(20_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return { json: await res.json(), from: source };
    }
    return { json: JSON.parse(await readFile(source, "utf8")), from: source };
  } catch (err) {
    console.warn(`[tracking-rules] could not load catalog from ${source}: ${err.message}`);
    return { json: null, from: `fallback (${err.message})` };
  }
}

async function formatJson(text, filepath) {
  try {
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(filepath)) ?? {};
    return await prettier.format(text, { ...config, filepath });
  } catch {
    return text.endsWith("\n") ? text : text + "\n";
  }
}

const { json, from } = await loadCatalog();
const usedFallback = json === null;
const providers = usedFallback ? FALLBACK_PROVIDERS : parseClearUrlsCatalog(json);
const { rules, report } = toRemoveParamsRules(providers, 1);

if (rules.length > DNR_LIMITS.maxStaticRulesPerRuleset) {
  throw new Error(
    `Generated ${rules.length} rules; static ruleset limit is ${DNR_LIMITS.maxStaticRulesPerRuleset}`,
  );
}
if (report.regexRules > DNR_LIMITS.maxRegexRules) {
  throw new Error(
    `Generated ${report.regexRules} regex rules; limit is ${DNR_LIMITS.maxRegexRules}`,
  );
}

const generatedAt = new Date().toISOString();
const meta = {
  generatedAt,
  source: usedFallback ? "bundled-fallback" : CATALOG_URL,
  usedFallback,
  providersTotal: report.providersTotal,
  providersUsed: report.providersUsed,
  providersSkipped: report.providersSkipped.length,
  rulesGenerated: report.rulesGenerated,
  removeParamRules: report.removeParamRules,
  exceptionRules: report.exceptionRules,
  regexRules: report.regexRules,
  literalParams: report.literalParams,
  expandedParams: report.expandedParams,
  skippedParamRegexes: report.skippedParamRegexes.length,
  exceptionsSkipped: report.exceptionsSkipped.length,
  rawRulesSkipped: report.rawRulesSkipped,
  redirectionsSkipped: report.redirectionsSkipped,
  referralMarketingSkipped: report.referralMarketingSkipped,
  providers: providers
    .filter((p) => !report.providersSkipped.some((s) => s.name === p.name))
    .map((p) => p.name),
};

const attribution = `# Attribution

The static ruleset in \`tracking-params.json\` is generated by
\`scripts/build-tracking-rules.mjs\` from the **ClearURLs** rule catalog.

- Project: ClearURLs by Kevin Roebert and contributors - https://github.com/ClearURLs/Addon
- Catalog: ${CATALOG_URL} (https://github.com/ClearURLs/Rules)
- Licence: GNU Lesser General Public License v3.0 (LGPL-3.0) -
  https://www.gnu.org/licenses/lgpl-3.0.html

The catalog data is converted, not copied verbatim: each provider's parameter
rules become \`declarativeNetRequest\` \`removeParams\` redirect rules and its
exceptions become \`allow\` rules. Regex-based parameter names are expanded to
literal names where possible; \`rawRules\`, \`redirections\`, \`referralMarketing\`
and \`completeProvider\` blocking entries are intentionally not converted.

Reroute is not affiliated with or endorsed by the ClearURLs project.

## Last generation

- Generated: ${generatedAt}
- Source: ${usedFallback ? "bundled minimal fallback (catalog unreachable)" : CATALOG_URL}
- Providers: ${report.providersUsed} used of ${report.providersTotal}
  (${report.providersSkipped.length} skipped)
- Rules: ${report.rulesGenerated} (${report.removeParamRules} removeParams,
  ${report.exceptionRules} exception allow rules, ${report.regexRules} regex-based)
- Parameters: ${report.literalParams} literal, ${report.expandedParams} expanded from regex,
  ${report.skippedParamRegexes.length} regex parameters not expressible
`;

await mkdir(outDir, { recursive: true });
await writeFile(rulesPath, await formatJson(JSON.stringify(rules), rulesPath), "utf8");
await writeFile(metaPath, await formatJson(JSON.stringify(meta), metaPath), "utf8");
await writeFile(attributionPath, attribution, "utf8");

console.log(`[tracking-rules] source: ${from}`);
console.log(
  `[tracking-rules] providers: ${report.providersUsed}/${report.providersTotal} used, ${report.providersSkipped.length} skipped`,
);
console.log(
  `[tracking-rules] rules: ${report.rulesGenerated} (${report.removeParamRules} removeParams, ${report.exceptionRules} exceptions, ${report.regexRules} regex)`,
);
console.log(
  `[tracking-rules] params: ${report.literalParams} literal, ${report.expandedParams} expanded, ${report.skippedParamRegexes.length} regex skipped`,
);
console.log(
  `[tracking-rules] not converted: ${report.rawRulesSkipped} rawRules, ${report.redirectionsSkipped} redirections, ${report.referralMarketingSkipped} referralMarketing, ${report.exceptionsSkipped.length} non-RE2 exceptions`,
);
if (report.providersSkipped.length) {
  console.log("[tracking-rules] skipped providers:");
  for (const s of report.providersSkipped) console.log(`  - ${s.name}: ${s.reason}`);
}
if (report.skippedParamRegexes.length) {
  console.log("[tracking-rules] parameter regexes with no literal expansion:");
  for (const s of report.skippedParamRegexes) console.log(`  - ${s.provider}: ${s.regex}`);
}
if (usedFallback) {
  console.warn("[tracking-rules] WARNING: wrote the bundled fallback set, not the live catalog.");
  process.exitCode = 2;
}
